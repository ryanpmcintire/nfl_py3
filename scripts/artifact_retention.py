import argparse
import re
from pathlib import Path

STAMP = re.compile(r"\d{8}T\d{6}Z")
TEXT_SUFFIXES = {".md", ".html", ".json", ".txt"}
KEEP_RULES = {
    "ledger": "keep every manifest, ledger and pointer-referenced run",
    "derived": "compact or prune unreferenced stamped derived files only after exact-directory owner approval",
    "capture": "keep raw point-in-time captures until retention and source-retrievability are evidenced",
}


def read_stamps(paths):
    found = set()
    for path in paths:
        try:
            found.update(STAMP.findall(path.read_text(encoding="utf-8", errors="ignore")))
        except OSError:
            continue
    return found


def reference_sets(root):
    pointers = sorted((root / "artifacts").glob("active_*.json"))
    docs = [p for p in (root / "docs").rglob("*") if p.is_file() and p.suffix in {".md", ".html"}]
    docs.append(root / "ROADMAP.md")
    return read_stamps(pointers), read_stamps(docs), pointers


def family_rule(name):
    lowered = name.lower()
    if any(k in lowered for k in ("ledger", "registry", "manifest", "active")):
        return KEEP_RULES["ledger"]
    if lowered in {"raw", "splash", "market", "players", "pbp", "quarterbacks"}:
        return KEEP_RULES["capture"]
    return KEEP_RULES["derived"]


def scan_family(directory, pointer_stamps, doc_stamps):
    row = {"files": 0, "bytes": 0, "ref": 0, "unref": 0, "unstamped": 0, "stamps": set(), "newest": None, "oldest": None}
    for path in directory.rglob("*"):
        try:
            if not path.is_file():
                continue
            size = path.stat().st_size
        except OSError:
            continue
        row["files"] += 1
        row["bytes"] += size
        stamps = STAMP.findall(path.as_posix())
        if not stamps:
            row["unstamped"] += size
            continue
        row["stamps"].update(stamps)
        if any(s in pointer_stamps or s in doc_stamps for s in stamps):
            row["ref"] += size
        else:
            row["unref"] += size
    if row["stamps"]:
        row["newest"] = max(row["stamps"])
        row["oldest"] = min(row["stamps"])
    return row


def human(n):
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024 or unit == "GiB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024


def main():
    parser = argparse.ArgumentParser(description="Read-only inventory of artifacts/ and data/ with referenced vs unreferenced bytes; deletes nothing")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--out", default="docs/artifact_retention.md")
    args = parser.parse_args()
    root = Path(args.root)
    pointer_stamps, doc_stamps, pointers = reference_sets(root)
    lines = [
        "# Artifact retention budget",
        "",
        "Generated by `scripts/artifact_retention.py`. Read-only: nothing is deleted or moved. "
        "Referenced means a stamp in the file path appears in an active pointer (`artifacts/active_*.json`) "
        "or in a document under `docs/` or `ROADMAP.md`. Unstamped bytes have no run stamp in the path and are not classified. "
        "Unreferenced is not a deletion reason; deleting any directory needs the owner's exact-directory approval.",
        "",
        f"Active pointers read: {', '.join(p.name for p in pointers)}",
        "",
    ]
    grand = {"files": 0, "bytes": 0, "ref": 0, "unref": 0, "unstamped": 0}
    all_rows = []
    for top in ("artifacts", "data"):
        base = root / top
        if not base.is_dir():
            continue
        lines += [f"## {top}/", "", "| Family | Files | Size | Referenced | Unreferenced stamped | Unstamped | Oldest stamp | Newest stamp | Proposed keep rule |", "|---|---:|---:|---:|---:|---:|---|---|---|"]
        rows = []
        for child in sorted(base.iterdir()):
            if child.is_dir():
                rows.append((child.name, scan_family(child, pointer_stamps, doc_stamps)))
            elif child.is_file():
                size = child.stat().st_size
                rows.append((child.name, {"files": 1, "bytes": size, "ref": 0, "unref": 0, "unstamped": size, "stamps": set(), "newest": None, "oldest": None}))
        rows.sort(key=lambda r: -r[1]["bytes"])
        for name, r in rows:
            for k in grand:
                grand[k] += r[k]
            all_rows.append((f"{top}/{name}", r))
            lines.append(f"| {name} | {r['files']} | {human(r['bytes'])} | {human(r['ref'])} | {human(r['unref'])} | {human(r['unstamped'])} | {r['oldest'] or '-'} | {r['newest'] or '-'} | {family_rule(name)} |")
        lines.append("")
    lines += [
        "## Totals",
        "",
        f"Files {grand['files']}, size {human(grand['bytes'])} ({grand['bytes']} bytes), referenced {human(grand['ref'])}, "
        f"unreferenced stamped {human(grand['unref'])}, unstamped {human(grand['unstamped'])}.",
        "",
        "## Deletion candidates (list only, owner approval required per exact directory)",
        "",
    ]
    cands = sorted(((n, r) for n, r in all_rows if r["unref"] > 0), key=lambda x: -x[1]["unref"])[:25]
    for n, r in cands:
        lines.append(f"- `{n}/`: {human(r['unref'])} unreferenced stamped of {human(r['bytes'])}")
    out = root / args.out
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    top5 = sorted(all_rows, key=lambda x: -x[1]["bytes"])[:5]
    print("TOTALS", grand)
    for n, r in top5:
        print("TOP", n, r["bytes"], human(r["bytes"]))


main()
